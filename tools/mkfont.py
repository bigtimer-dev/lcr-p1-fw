#!/usr/bin/env python3
"""Convert Terminus BDF fonts (fonts/*.bdf, SIL OFL 1.1) to C bitmap tables.

    python3 tools/mkfont.py > src/font_data.c

Each font covers ASCII 32..126 plus extra glyphs mapped to codes 127.. (see EXTRA).
Rows are stored MSB-first, (w + 7) / 8 bytes per row.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXTRA = [0x03A9, 0x00B5, 0x00B0]     # 127 = Ohm, 128 = micro, 129 = degree
FONTS = [('font16', 'ter-u16n.bdf'), ('font24', 'ter-u24b.bdf')]


def load(path):
    glyphs, cur, rows, w, h = {}, None, None, 0, 0
    for line in open(path, encoding='ascii'):
        f = line.split()
        if not f:
            continue
        if f[0] == 'FONTBOUNDINGBOX':
            w, h = int(f[1]), int(f[2])
        elif f[0] == 'ENCODING':
            cur = int(f[1])
        elif f[0] == 'BITMAP':
            rows = []
        elif f[0] == 'ENDCHAR':
            glyphs[cur], rows = rows, None
        elif rows is not None:
            rows.append(int(f[0], 16))
    return w, h, glyphs


def main():
    out = ['/* Generated by tools/mkfont.py from Terminus Font 4.49.1 BDF files.',
           ' * Terminus Font: Copyright (C) 2020 Dimitar Toshkov Zhekov, SIL Open Font License 1.1',
           ' * (fonts/OFL.TXT). Converted to bitmap tables; glyph shapes unchanged. */',
           '#include "font.h"', '']
    for name, fn in FONTS:
        w, h, g = load(os.path.join(ROOT, 'fonts', fn))
        bpr = (w + 7) // 8
        codes = list(range(32, 127)) + EXTRA
        data = []
        for c in codes:
            rows = g.get(c)
            assert rows and len(rows) == h, (fn, hex(c))
            for r in rows:
                data += list(r.to_bytes(bpr, 'big'))     # BDF rows are already left-aligned per byte
        out.append(f'static const uint8_t {name}_bits[{len(data)}] = {{')
        for i in range(0, len(data), 16):
            out.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
        out.append('};')
        out.append(f'const struct font {name} = {{ {w}, {h}, {bpr}, 32, {len(codes)}, {name}_bits }};')
        out.append('')
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
