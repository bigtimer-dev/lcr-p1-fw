#!/usr/bin/env python3
"""Embed a 6 KB bootloader image in the installer: build/boot/blob.c.

    boot/mkblob.py BLOB.bin NAME STOCK_CRC > build/boot/blob.c

STOCK_CRC: CRC32 of FNIRSI's loader as dumped from a meter (only the number; the dump is not in the repo).
"""
import sys
import zlib

data = open(sys.argv[1], 'rb').read()
assert len(data) == 0x1800, f'{sys.argv[1]}: {len(data)} bytes, expected 6144'
assert data[:4] != b'\xff' * 4, 'no initial SP'
print('/* generated by boot/mkblob.py */')
print('#include <stdint.h>')
print(f'const char blob_name[] = "{sys.argv[2]}";')
print(f'const uint32_t blob_crc = 0x{zlib.crc32(data):08x}u;')
print(f'const uint32_t stock_crc = {sys.argv[3]}u;')
print('const uint8_t blob[6144] = {')
for i in range(0, len(data), 16):
    print('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
print('};')
