#!/usr/bin/env python3
"""Terminus 8x16 (fonts/ter-u16n.bdf, SIL OFL 1.1) as boot/font.c: only the characters that appear in the
string literals of boot/bl.c (plus hex digits; lowercase maps to the capitals), with a 95-entry map for ASCII 32..126 (0xFF = blank).

    python3 boot/mkfont.py > boot/font.c
"""
import os
import re
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'tools'))
from mkfont import ROOT, load  # noqa: E402

src = open(os.path.join(HERE, 'bl.c')).read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
src = re.sub(r'__asm[^;]*;', '', src)
used = set(''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', src))) | set('0123456789ABCDEF.?')
chars = sorted({c.upper() for c in used if 32 < ord(c) < 127})   # screen text is shown in capitals
w, h, g = load(os.path.join(ROOT, 'fonts', 'ter-u16n.bdf'))
assert (w, h) == (8, 16)
cmap = [chars.index(chr(c).upper()) if chr(c).upper() in chars else 0xFF for c in range(32, 127)]
data = [r for c in chars for r in g[ord(c)]]
out = ['/* Generated by boot/mkfont.py from Terminus Font 4.49.1 (ter-u16n.bdf), characters used by bl.c only, lowercase shown as capitals.',
       ' * Terminus Font: Copyright (C) 2020 Dimitar Toshkov Zhekov, SIL Open Font License 1.1 (fonts/OFL.TXT). */',
       '#include <stdint.h>', f'/* {"".join(chars)} */',
       'const uint8_t bl_font_map[95] = {']
out += ['    ' + ', '.join(f'{b:3d}' for b in cmap[i:i + 16]) + ',' for i in range(0, 95, 16)]
out += ['};', f'const uint8_t bl_font[{len(data)}] = {{']
out += ['    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',' for i in range(0, len(data), 16)]
out.append('};')
print('\n'.join(out))
